const PROFESSION_KEYS: Record<string, string> = {
  'electrician': 'service.electrician',
  'plumber': 'service.plumber',
  'home cleaning': 'service.homeCleaning',
  'painter': 'service.painter',
  'carpenter': 'service.carpenter',
  'ac repair': 'service.acRepair',
  'mason': 'service.mason',
  'gardener': 'service.gardener',
};

export function translateProfession(prof: string | undefined, t: (k: string) => string): string {
  if (!prof) return t('services.serviceProvider');
  const key = PROFESSION_KEYS[prof.toLowerCase()];
  return key ? t(key) : prof;
}

export function translateName(name: string, isNp: boolean): string {
  if (!isNp || !name) return name;
  const words = name.trim().toLowerCase().split(/\s+/);

  // If we have translations for any word in our dictionary, return them
  const hasTrans = words.some(word => word in NAME_TRANSLITERATIONS);
  if (hasTrans) {
    return words.map(word => NAME_TRANSLITERATIONS[word] || word).map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  }
  
  return name;
}
